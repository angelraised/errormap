export function getBrowserLanguage(): Language {
  const browserLang = navigator.language.toLowerCase();
  if (browserLang.startsWith('ru')) return 'ru';
  if (browserLang.startsWith('kk') || browserLang.startsWith('kz')) return 'kz';
  return 'en';
}
